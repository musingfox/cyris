#!/usr/bin/env python3
"""Build the shared settings page into the hosted Worker (ADR-0043).

The hosted Worker runs no Python, so the page `TriageServer` renders per request from
`settings.html.j2` is rendered here, at build time, once per UI catalog, and written with every
`/static/` file it loads into one JSON module the Worker imports:
`workers/app/src/shared_settings.build.json`, which git ignores. `wrangler.hosted.toml`'s `[build]`
runs this before each deploy, and vitest's global setup before each run.

What the file holds, so the Worker serves the page exactly as the local edition does:

* `pages`: each catalog's page, with the SHA-256 of each inline script and style, which the
  Worker's policy allows and nothing else inline.
* `files`: each `/static/` path a page loads, and each module those import, with its type and its
  ETag; and each catalog's browser messages, `/static/i18n/<tag>.json`, as `TriageServer` serves
  them.
* `sent_as_shown` and `languages`: the two parts of `GET /api/settings` that only the Python side
  can answer, as `TriageServer` answers them.

Usage: `uv run python scripts/build_shared_settings.py [--out PATH]`.
"""

import argparse
import base64
import hashlib
import json
import re
import sys
from pathlib import Path, PurePosixPath

from cyris.entrypoints.triage_server import (
    BROWSER_MESSAGES,
    STATIC_DIR,
    render_settings_page,
    sent_as_shown,
)
from cyris.i18n import browser_file, catalogs
from cyris.service_layer.prompts import _language_names

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "workers/app/src/shared_settings.build.json"
STATIC = "/static/"
TYPES = {
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json",
}
# What a page names of this server's own: its scripts and styles, and the catalog file its meta
# names. A module's `import ... from "./x.js"` names another.
LOADS = re.compile(r'<(?:script|link)\b[^>]*\b(?:src|href)="(/static/[^"]+)"')
CATALOG = re.compile(r'<meta name="i18n-catalog" content="(/static/i18n/[^"]+)">')
IMPORTS = re.compile(r"""^\s*import\b[^;]*?\bfrom\s+["'](\./[^"']+)["']""", re.MULTILINE)
INLINE = {
    "script_hashes": re.compile(r"<script>(.*?)</script>", re.DOTALL),
    "style_hashes": re.compile(r"<style>(.*?)</style>", re.DOTALL),
}


def _hash(text: str) -> str:
    """A CSP source for an inline block: `sha256-` and the base64 of its UTF-8's digest."""
    return "sha256-" + base64.b64encode(hashlib.sha256(text.encode()).digest()).decode()


def _etag(body: str) -> str:
    return f'"{hashlib.sha256(body.encode()).hexdigest()[:32]}"'


def _static(path: str) -> dict[str, str]:
    """One file under `static/`, by its served path, as the Worker serves it."""
    relative = PurePosixPath(path).relative_to(STATIC)
    source = (STATIC_DIR / relative).resolve()
    if not source.is_relative_to(STATIC_DIR.resolve()):
        raise ValueError(f"{path} is outside {STATIC_DIR}")
    body = source.read_text(encoding="utf-8")
    return {"type": TYPES[source.suffix], "body": body, "etag": _etag(body)}


def _module_closure(paths: list[str]) -> list[str]:
    """`paths` and every module the scripts among them import, relatively, in first-seen order."""
    seen: list[str] = []
    queue = list(paths)
    while queue:
        path = queue.pop(0)
        if path in seen:
            continue
        seen.append(path)
        if path.endswith(".js"):
            body = _static(path)["body"]
            parent = PurePosixPath(path).parent
            queue += [str(parent / name.removeprefix("./")) for name in IMPORTS.findall(body)]
    return seen


def build() -> dict:
    pages: dict[str, dict] = {}
    files: dict[str, dict[str, str]] = {}
    loaded: list[str] = []
    for tag in catalogs():
        html = render_settings_page(tag)
        pages[tag] = {"html": html}
        for name, rule in INLINE.items():
            pages[tag][name] = [_hash(block) for block in rule.findall(html)]
        loaded += [path for path in LOADS.findall(html) if path not in loaded]
        served = browser_file(tag, BROWSER_MESSAGES)
        catalog_path = CATALOG.search(html)[1]
        files[catalog_path] = {
            "type": TYPES[".json"],
            "body": served.body.decode(),
            "etag": served.etag,
        }
    for path in _module_closure(loaded):
        files[path] = _static(path)
    return {
        "_comment": "GENERATED by scripts/build_shared_settings.py; do not edit (ADR-0043).",
        "pages": pages,
        "files": dict(sorted(files.items())),
        "sent_as_shown": sent_as_shown(),
        "languages": [{"tag": tag, "name": name} for tag, name in _language_names().items()],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    built = build()
    args.out.write_text(json.dumps(built, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{args.out}: {len(built['pages'])} pages, {len(built['files'])} files", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
